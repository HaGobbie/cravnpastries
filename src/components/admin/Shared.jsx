/* ── CopyButton ── */
export const CopyButton = ({ text, className = '' }) => {
  const [copied, setCopied] = useState(false);
  const handle = (e) => {
    e.stopPropagation();
    navigator.clipboard.writeText(text).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 1800);
    });
  };
  return (
    <button className={`copy-id-btn ${copied ? 'copied' : ''} ${className}`} onClick={handle} title="Copy to clipboard">
      {copied
        ? <><Icon name="check" size={9} /> Copied!</>
        : <><Icon name="copy"  size={9} /> Copy</>}
    </button>
  );
};

